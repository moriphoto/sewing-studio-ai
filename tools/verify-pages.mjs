#!/usr/bin/env node
// Verifies each model's manual links and "where to look" page numbers.
//  - every link is requested (HTTP status recorded; links marked blocked:true are expected to refuse scripts)
//  - for each manual, the PDF is downloaded to $MANUAL_CACHE (default /tmp/man), converted with pdftotext,
//    and every page row must contain its `find` phrase on PDF page (printed + offset).
// Output: data/manual-verification.json and js/machines/verified-pages.js (only rows that pass are shipped).
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, writeFileSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { MODELS } from '../js/machines/index.js';

const CACHE = process.env.MANUAL_CACHE || '/tmp/man';
mkdirSync(CACHE, { recursive: true });
const norm = (s) => s.replace(/[\s\u00a0]+/g, ' ').toLowerCase();
const sh = (cmd, args, o = {}) => execFileSync(cmd, args, { encoding: 'utf8', maxBuffer: 200e6, ...o });
const status = (url) => {
  try { return Number(sh('curl', ['-sL', '-o', '/dev/null', '-m', '40', '-A', 'Mozilla/5.0', '-r', '0-0', '-w', '%{http_code}', url]).trim()); } catch { return 0; }
};
// ONLY=<regex> re-checks just the matching models and carries the other models' previous results over.
const ONLY = process.env.ONLY ? new RegExp(process.env.ONLY) : null;
const prev = ONLY && existsSync('data/manual-verification.json') ? JSON.parse(readFileSync('data/manual-verification.json', 'utf8')).models : {};
const prevShipped = ONLY ? Object.fromEntries(Object.entries(prev).map(([id, r]) => [id, r.pages.filter(x => x.ok).map(x => x.key)])) : {};
const report = { generated: new Date().toISOString(), models: {} };
const shipped = {};
let bad = 0;
for (const m of MODELS) {
  if (ONLY && !ONLY.test(m.id) && prev[m.id]) { report.models[m.id] = prev[m.id]; shipped[m.id] = prevShipped[m.id]; continue; }
  const r = { links: [], pages: [] };
  for (const l of m.links) {
    const s = status(l.url);
    const ok = s === 200 || s === 206;
    r.links.push({ title: l.title, url: l.url, http: s, ok, blockedExpected: !!l.blocked });
    if (!ok && !l.blocked) { bad++; console.error(`LINK FAIL ${m.id}: ${s} ${l.url}`); }
  }
  shipped[m.id] = [];
  if (m.manual) {
    const full = m.links.find(l => l.doc === 'full');
    const pdf = path.join(CACHE, m.manual.file);
    if (!existsSync(pdf)) sh('curl', ['-sL', '-m', '300', '-A', 'Mozilla/5.0', '-o', pdf, full.url]);
    const txt = sh('pdftotext', ['-layout', pdf, '-']).split('\f');
    r.pdfPages = txt.length - 1;
    for (const p of m.manual.pages) {
      const idx = p.printed + m.manual.offset;
      const hay = norm(txt[idx - 1] || '');
      const ok = hay.includes(norm(p.find));
      r.pages.push({ key: p.key, topic: p.topic, printed: p.printed, pdfIndex: idx, find: p.find, ok });
      if (ok) shipped[m.id].push(p.key); else { bad++; console.error(`PAGE FAIL ${m.id}: "${p.find}" not on pdf page ${idx} (printed ${p.printed})`); }
    }
  }
  report.models[m.id] = r;
  const pass = r.pages.filter(x => x.ok).length;
  console.log(`${m.id.padEnd(24)} links ${r.links.filter(x => x.ok).length}/${r.links.length}${r.links.some(x => !x.ok && x.blockedExpected) ? ' (blocked: ' + r.links.filter(x => !x.ok).map(x => x.http).join(',') + ')' : ''}  pages ${pass}/${r.pages.length}`);
}
mkdirSync('data', { recursive: true });
writeFileSync('data/manual-verification.json', JSON.stringify(report, null, 2));
writeFileSync('js/machines/verified-pages.js', `// GENERATED by tools/verify-pages.mjs – only page rows that passed the check.\nexport const VERIFIED = ${JSON.stringify(shipped, null, 1)};\n`);
console.log(bad ? `\n${bad} problem(s)` : '\nAll links/pages verified (blocked links excepted).');
process.exit(bad ? 1 : 0);
